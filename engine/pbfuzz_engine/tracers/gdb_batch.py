"""The primary tracer: gdb driven through its Python API in batch mode.

One traced run is one ``gdb -batch -x script.py`` invocation. There is no
interactive session, no FIFO and no DAP adapter: the script sets the
breakpoints, lets gdb auto-continue through them, and writes a JSON report that
this module parses. Everything that can be tested without gdb — building the
script, building the run line, parsing the report, parsing ``info breakpoints``
— is a pure function here.

Breakpoints are created with ``set breakpoint pending on``, so a line gdb
cannot bind becomes a *pending* breakpoint rather than an error, and is
reported as ``resolved: false``. That distinction is the whole point: zero hits
on a bound breakpoint means "not executed", while an unbound breakpoint means
"the build has no line info for this location" and has different remedies.

:module: pbfuzz_engine.tracers.gdb_batch
"""

