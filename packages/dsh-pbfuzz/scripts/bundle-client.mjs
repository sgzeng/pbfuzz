#!/usr/bin/env node
/**
 * Bundle src/client/index.ts into the single classic-script artifact lib/client.js,
 * then prove the artifact is loadable before anyone opens a browser.
 *
 * WHY THIS SHAPE. DSH serves a plugin's lib/client.js as a CLASSIC <script>. A
 * classic script containing `import`/`export` is a syntax error that surfaces
 * only as a blank page in the browser, with nothing in the Node logs. The DSH
 * loader contract (packages/client/tsdown.client.ts in the harness) is a
 * closure factory:
 *
 *   window.__ModuleLoader__.load({ id, factory: (require) => { ...; return module.exports } })
 *
 * where `require` is the loader's module table (react, cordis, ui-* ...). So we
 * use esbuild `bundle: true` with `format: 'cjs'` wrapped in that banner/footer.
 * `format: 'iife'` is NOT usable here: externals become a top-level `__require`
 * shim that throws "Dynamic require is not supported" at runtime, and the
 * exports never reach the loader. The cjs body inside the factory closure is
 * the IIFE-equivalent: one self-contained expression, no module syntax, no
 * global require.
 *
 * Platform modules stay external (provided by the host page); everything else
 * is inlined. Any other @deepseek-ai value import fails the build (bundle
 * purity: cross-plugin collaboration goes through cordis services).
 *
 * SELF-CHECKS (any failure exits 1):
 *   1. classic-script: the output compiles as a classic script (vm.Script), and
 *      no line starts with `import`/`export` module syntax;
 *   2. loader handoff: running the file calls window.__ModuleLoader__.load
 *      exactly once with the package id and a factory, WITHOUT any global
 *      `require` (a top-level require would throw ReferenceError here);
 *   3. externals: every require() the factory makes is on the platform list;
 *      materializing the factory against stubs yields `apply` + `inject`;
 *   4. schema parity: the card's field table equals the leaves of
 *      contracts/pbfuzz-settings.schema.json (path, kind, default, enum, bounds).
 *
 * Usage: node scripts/bundle-client.mjs [--check]   (--check: verify lib/client.js without rebuilding)
 */
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = resolve(pkgRoot, '../..')
const pkg = JSON.parse(readFileSync(resolve(pkgRoot, 'package.json'), 'utf8'))
const ID = pkg.name
const OUT = resolve(pkgRoot, 'lib/client.js')
const checkOnly = process.argv.includes('--check')

/** The DSH shell's module table (packages/client/web/src/platform.ts, pinned by HARNESS_COMMIT). */
const PLATFORM_MODULES = [
  'react', 'react/jsx-runtime', 'react-dom', 'react-dom/client', '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

const failures = []
const fail = (msg) => { failures.push(msg) }

const purity = {
  name: 'pbfuzz-client-bundle-purity',
  setup(b) {
    b.onResolve({ filter: /^@deepseek-ai\// }, (args) => {
      if (PLATFORM_MODULES.includes(args.path)) return { path: args.path, external: true }
      return {
        errors: [{
          text: `client bundle purity: value import of "${args.path}" — only platform modules may be imported as values; `
            + 'use `import type` or a cordis service',
        }],
      }
    })
  },
}

if (!checkOnly) {
  mkdirSync(dirname(OUT), { recursive: true })
  await build({
    entryPoints: [resolve(pkgRoot, 'src/client/index.ts')],
    outfile: OUT,
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2020',
    jsx: 'automatic',
    external: PLATFORM_MODULES,
    plugins: [purity],
    define: { 'process.env.NODE_ENV': '"production"' },
    legalComments: 'inline',
    charset: 'utf8',
    logLevel: 'warning',
    banner: {
      js: `/* ${ID} v${pkg.version} client bundle — generated by scripts/bundle-client.mjs from src/client; do not edit. */\n`
        + `window.__ModuleLoader__.load({ id: ${JSON.stringify(ID)}, factory: (require) => {\nvar module = { exports: {} }; var exports = module.exports;`,
    },
    footer: { js: 'return module.exports; } });' },
  })
}

const out = readFileSync(OUT, 'utf8')

// 1. classic-script syntax
try {
  new vm.Script(out, { filename: 'lib/client.js' })
} catch (error) {
  fail(`not a valid classic script: ${error.message}`)
}
// Keyword followed by whitespace/brace/star/quote/paren — so esbuild's own
// identifiers like `import_react` never match.
const moduleLine = out.split('\n').findIndex(line => /^\s*(import(\s+[\w{*'"]|\s*[{*'"(])|export(\s+[\w{*]|\s*[{*]))/.test(line))
if (moduleLine !== -1) fail(`module syntax at line ${moduleLine + 1}: ${out.split('\n')[moduleLine].slice(0, 80)}`)
if (!out.includes('window.__ModuleLoader__.load(')) fail('missing window.__ModuleLoader__.load call')

// 2. loader handoff with no global require
const registrations = []
const sandbox = { window: { __ModuleLoader__: { load: r => registrations.push(r) } }, console }
try {
  vm.runInNewContext(out, sandbox, { filename: 'lib/client.js' })
} catch (error) {
  fail(`top-level evaluation threw (a top-level require/import would): ${error.message}`)
}
if (registrations.length !== 1) fail(`expected exactly one __ModuleLoader__.load call, got ${registrations.length}`)
const reg = registrations[0]
if (reg !== undefined && reg.id !== ID) fail(`registration id ${reg.id} !== ${ID}`)
if (reg !== undefined && typeof reg.factory !== 'function') fail('registration has no factory function')

// 3. externals + materialization
const requested = new Set()
if (typeof reg?.factory === 'function') {
  const stub = () => new Proxy(function stubFn() {}, {
    get: (_t, key) => key === '__esModule' ? false : key === Symbol.toPrimitive ? () => '' : stub(),
    apply: () => stub(),
    construct: () => stub(),
  })
  const req = (spec) => {
    requested.add(spec)
    if (!PLATFORM_MODULES.includes(spec)) throw new Error(`require("${spec}") is not a platform module`)
    return stub()
  }
  try {
    const exportsObj = reg.factory(req)
    if (typeof exportsObj?.apply !== 'function') fail('factory exports no apply()')
    if (!Array.isArray(exportsObj?.inject)) fail('factory exports no inject[]')
    else if (JSON.stringify(exportsObj.inject) !== JSON.stringify(['slots', 'locale', 'remote', 'remote.session', 'remote.commands', 'remote.settings', 'sessions', 'configForms'])) {
      fail(`unexpected inject ${JSON.stringify(exportsObj.inject)}`)
    }
  } catch (error) {
    fail(`factory materialization failed: ${error.message}`)
  }
}
for (const m of out.matchAll(/\brequire\(\s*["']([^"']+)["']\s*\)/g)) {
  if (!PLATFORM_MODULES.includes(m[1])) fail(`bundle requires non-platform module "${m[1]}"`)
}

// 4. schema parity
const schema = JSON.parse(readFileSync(resolve(repoRoot, 'contracts/pbfuzz-settings.schema.json'), 'utf8'))
const leaves = []
for (const [group, sub] of Object.entries(schema.properties)) {
  for (const [key, leaf] of Object.entries(sub.properties)) leaves.push({ id: `${group}.${key}`, group, leaf })
}
const modelSrc = await build({
  entryPoints: [resolve(pkgRoot, 'src/client/settings-model.ts')], bundle: true, format: 'esm', write: false, platform: 'neutral',
})
const { FIELDS, GROUPS } = await import(`data:text/javascript;base64,${Buffer.from(modelSrc.outputFiles[0].text).toString('base64')}`)
const kindOf = (leaf) => {
  if (leaf.type === 'boolean') return 'toggle'
  if (leaf.type === 'integer') return 'integer'
  if (leaf.type === 'number') return 'number'
  if (leaf.type === 'array') return 'multi'
  if (leaf.type === 'string') return leaf.enum !== undefined ? 'enum' : 'text'
  return `?${leaf.type}`
}
if (JSON.stringify(GROUPS) !== JSON.stringify(Object.keys(schema.properties))) {
  fail(`groups ${JSON.stringify(GROUPS)} != schema ${JSON.stringify(Object.keys(schema.properties))}`)
}
const byId = new Map(FIELDS.map(f => [f.id, f]))
for (const { id, group, leaf } of leaves) {
  const f = byId.get(id)
  if (f === undefined) { fail(`schema field ${id} missing from the card`); continue }
  const expect = {
    group, kind: kindOf(leaf), default: leaf.default,
    options: leaf.enum ?? leaf.items?.enum, min: leaf.minimum, max: leaf.maximum, exclusiveMin: leaf.exclusiveMinimum,
  }
  for (const [k, v] of Object.entries(expect)) {
    if (JSON.stringify(f[k]) !== JSON.stringify(v)) fail(`${id}.${k}: card ${JSON.stringify(f[k])} != schema ${JSON.stringify(v)}`)
  }
}
for (const f of FIELDS) if (!leaves.some(l => l.id === f.id)) fail(`card field ${f.id} is not in the schema`)

if (failures.length > 0) {
  for (const f of failures) console.error(`✗ ${f}`)
  process.exit(1)
}
console.log(`✔ lib/client.js ${(out.length / 1024).toFixed(1)} kB — classic-safe, __ModuleLoader__.load(${ID}) once, `
  + `requires [${[...requested].sort().join(', ')}]; card ⇔ schema parity ${FIELDS.length}/${leaves.length} fields`)
